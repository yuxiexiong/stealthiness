"""TOY-VD-01 Stage B-1: PurMM fairness hardening, fully offline (contract 69fb4f9).

The formal run persisted PurMM's per-layer high-attention indices, so every
combination-policy variant (which layers count as "deep", dilation radius, and the
combine rule) is recomputable without the model. For each variant the mask is
rebuilt, the ORDER is regenerated by the frozen repair.diagnosis_truth.predictions()
on a rankings-swapped copy of the sealed public packet, and recall@k comes from the
frozen _discovery over Stage-A's graded rows. Selection on the first 5 scene
clusters (dev, frozen rule: sorted cluster ids); the single dev-best variant is then
evaluated on the remaining confirm clusters against the recorded random-order
recall distribution (95th percentile bar), per K-B.

Usage: python toy_vd_stage_b_purmm.py --runs runs/diagnosis-truth-formal \
    --output runs/toy-vd/stage-b-purmm.json
"""

import argparse
import json
from pathlib import Path

from repair.diagnosis_truth import _discovery, predictions
from toy_vd_stage_a import graded_rows

DEV_CLUSTERS = 5           # first N sorted cluster ids
SELECT_BUDGET = 4          # dev selection on recall@4, tie-break recall@1
CONFIRM_BUDGETS = (1, 4)


def dilate(indices, radius):
    if radius == 0:
        return set(indices)
    grown = set()
    for index in indices:
        y, x = divmod(index, 24)
        for row in range(max(0, y - radius), min(24, y + radius + 1)):
            for col in range(max(0, x - radius), min(24, x + radius + 1)):
                grown.add(row * 24 + col)
    return grown


def variant_mask(per_layer, deep_mode, radius, rule):
    layers = [set(v) for v in per_layer]
    union = set().union(*layers)
    if deep_mode == "half":
        deep = set().union(*layers[len(layers) // 2:])
    elif deep_mode == "quarter":
        deep = set().union(*layers[3 * len(layers) // 4:])
    else:  # "all"
        deep = union
    retained = dilate(deep, radius)
    if rule == "intersect":
        mask = union & retained
    elif rule == "union":
        mask = union
    else:  # "deep"
        mask = deep
    return sorted(mask)


VARIANTS = [
    {"deep": d, "radius": r, "rule": rule}
    for d in ("half", "quarter", "all")
    for r in (0, 1, 2)
    for rule in ("intersect", "union", "deep")
    if not (rule in ("union", "deep") and r != 1)  # radius only matters for intersect
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    units = []
    for path in sorted(Path(args.runs).iterdir()):
        if not path.name.endswith("-abnormal") or not (path / "selectors.json").exists():
            continue
        packet = json.loads((path / "public.json").read_text())
        oracle = json.loads((path / "oracle.json").read_text())
        selectors = json.loads((path / "selectors.json").read_text())
        submissions = {s["method"]: s for s in
                       json.loads((path / "submissions.json").read_text())}
        metrics = {m["method"]: m for m in json.loads((path / "metrics.json").read_text())}
        units.append({"name": path.name, "cluster": metrics["G"]["cluster_id"],
                      "packet": packet, "rows": graded_rows(packet, oracle),
                      "per_layer": selectors["external"]["purmm"]
                                            ["per_layer_high_attention_indices"],
                      "recorded_mask": selectors["external"]["purmm"]
                                                ["selected_visual_indices"],
                      "random_order": submissions["random"]["order"]})

    clusters = sorted({u["cluster"] for u in units})
    dev, confirm = set(clusters[:DEV_CLUSTERS]), set(clusters[DEV_CLUSTERS:])

    def recall_for_mask(unit, mask, k):
        packet = dict(unit["packet"])
        packet["rankings"] = dict(packet.get("rankings", {}))
        packet["rankings"]["purmm"] = sorted(set(mask))
        order = predictions(packet, "purmm")["order"]
        limited = _discovery(unit["rows"], order[:k])["16"]["recall"]
        return limited

    def cluster_mean(pairs):
        per = {}
        for cluster, value in pairs:
            per.setdefault(cluster, []).append(value)
        means = [sum(v) / len(v) for v in per.values()]
        return sum(means) / len(means), per

    report = {"variants": []}
    best = None
    for variant in VARIANTS:
        pairs4, pairs1 = [], []
        for unit in (u for u in units if u["cluster"] in dev):
            mask = variant_mask(unit["per_layer"], variant["deep"], variant["radius"],
                                variant["rule"])
            pairs4.append((unit["cluster"], recall_for_mask(unit, mask, 4)))
            pairs1.append((unit["cluster"], recall_for_mask(unit, mask, 1)))
        mean4, _ = cluster_mean(pairs4)
        mean1, _ = cluster_mean(pairs1)
        row = {**variant, "dev_recall_at_4": mean4, "dev_recall_at_1": mean1}
        report["variants"].append(row)
        if best is None or (mean4, mean1) > (best["dev_recall_at_4"], best["dev_recall_at_1"]):
            best = row
    report["dev_clusters"] = sorted(dev)
    report["selected_variant"] = best

    confirm_result = {}
    for k in CONFIRM_BUDGETS:
        hardened_pairs, random_pairs, default_pairs = [], [], []
        for unit in (u for u in units if u["cluster"] in confirm):
            mask = variant_mask(unit["per_layer"], best["deep"], best["radius"],
                                best["rule"])
            hardened_pairs.append((unit["cluster"], recall_for_mask(unit, mask, k)))
            random_pairs.append((unit["cluster"],
                                 _discovery(unit["rows"], unit["random_order"][:k])
                                 ["16"]["recall"]))
            default_pairs.append((unit["cluster"],
                                  recall_for_mask(unit, unit["recorded_mask"], k)))
        hardened_mean, _ = cluster_mean(hardened_pairs)
        default_mean, _ = cluster_mean(default_pairs)
        _, random_per = cluster_mean(random_pairs)
        random_cluster_means = sorted(sum(v) / len(v) for v in random_per.values())
        bar = random_cluster_means[min(len(random_cluster_means) - 1,
                                       int(0.95 * len(random_cluster_means)))]
        confirm_result[f"k={k}"] = {
            "hardened_mean": hardened_mean, "default_mean": default_mean,
            "random_null_p95_bar": bar,
            "hardened_le_bar": bool(hardened_mean <= bar)}
    report["confirm_clusters"] = sorted(confirm)
    report["k_b_confirm"] = confirm_result
    report["k_b_verdict"] = ("HEADLINE_HARDENED"
                             if all(v["hardened_le_bar"] for v in confirm_result.values())
                             else "HEADLINE_DEGRADED_default_adaptation_only")

    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: report[k] for k in
                      ("selected_variant", "k_b_confirm", "k_b_verdict")}, indent=2))


if __name__ == "__main__":
    main()
